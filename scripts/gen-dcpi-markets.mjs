#!/usr/bin/env node
// Regenerates lib/dcpi-markets.data.mjs: every market the live DCPI index
// tracks, so execute_plan's market_outlook class can read "power outlook for
// <any tracked market>" as that market (lib/dcpi-market-match.mjs).
//
//   DCHUB_KEY=<key> node scripts/gen-dcpi-markets.mjs      # fetch + write if valid (daily-manifest-sync)
//   node scripts/gen-dcpi-markets.mjs <scores.json>        # from a saved /api/v1/dcpi/scores body
//
// A key is needed: anonymous /api/v1/dcpi/scores returns 10 of the 336 rows.
//
// FAIL-CLOSED, like the other refresh-* scripts: a fetch error, a body that is
// not the whole index (count < _total_available), fewer than 300 rows, or a
// list that lost more than 10% of the committed markets → log and exit 0
// WITHOUT writing; the committed table stays in force. The file is rewritten
// only when the market rows change, so a new as_of alone opens no PR.
//
// Each row: [slug, display name, states, iso, rto, aliases]. `iso` is the
// index's own grid label (WECC, SOCO, TVA, ENTSOE-DE …). `rto` is that label
// only when it is a US RTO execute_plan accepts as an iso arg, else null.
// Aliases are the normalized name plus the hand-kept EXTRA list below; review
// the diff when the table moves — a new market whose name is an ordinary word
// belongs in QUALIFIER_REQUIRED in the matcher.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { normPlace } from '../lib/dcpi-market-norm.mjs';

const OUT = new URL('../lib/dcpi-markets.data.mjs', import.meta.url);
const URL_ = 'https://dchub.cloud/api/v1/dcpi/scores?limit=500';
const MIN_ROWS = 300;
const MAX_LOSS = 0.10;
const RTOS = new Set(['ERCOT', 'PJM', 'MISO', 'SPP', 'CAISO', 'NYISO', 'ISONE']);
// Other names people use for a tracked market. Never a nearby market's name.
const EXTRA = {
  dallas: ['dallas fort worth', 'dfw'],
  'new-york': ['new york city', 'nyc'],
  'salt-lake-city': ['salt lake'],
  'midland-tx': ['midland', 'odessa', 'permian basin'],
  'the-woodlands': ['woodlands'],
  'virgin-islands': ['virgin islands', 'usvi'],
  'appalachia-coal': ['appalachia'],
  'upper-michigan': ['upper peninsula'],
  bangalore: ['bengaluru'],
  'ho-chi-minh-city': ['saigon', 'hcmc'],
  'mexico-city': ['cdmx'],
  'johor': ['johor bahru'],
  'bridgewater-township': ['bridgewater'],
  "coeur-d'alene": ['coeur d alene'],
  dc: ['washington dc', 'washington, dc', 'district of columbia'],
};
// A name followed by its own state ("Portland, ME") is the base name plus a
// qualifier, so "portland" is the alias. DC is the exception: its base name is
// a state.
const NO_BASE = new Set(['dc']);
// Markets that span more than one state.
const STATES = { 'kansas-city': ['MO', 'KS'] };

const titled = (n) => (n === n.toUpperCase() ? n.toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase()) : n);

// Exported for tests: the rows this script would write for a scores body.
export function buildRows(scores) {
  return scores.map((r) => {
    const slug = String(r.market_slug), state = String(r.state || '').toUpperCase(), iso = String(r.iso || '').toUpperCase() || null;
    const name = titled(String(r.market_name || slug));
    const aliases = new Set();
    const full = normPlace(name);
    const q = full.match(/^(.*), ([a-z]{2})$/);
    if (q && q[2].toUpperCase() === state) { if (!NO_BASE.has(slug)) aliases.add(q[1]); }
    else aliases.add(full.replace(/,/g, ''));
    for (const a of EXTRA[slug] || []) aliases.add(normPlace(a));
    return [slug, name, STATES[slug] || [state], iso, RTOS.has(iso) ? iso : null, [...aliases].sort()];
  }).sort((a, b) => a[0].localeCompare(b[0]));
}

// Why a body must not replace the committed table, or null when it may.
export function refuseReason(body, current) {
  const scores = body && Array.isArray(body.scores) ? body.scores : null;
  if (!scores) return 'no scores array';
  if (body._total_available != null && scores.length < body._total_available) {
    return `partial list: ${scores.length} of ${body._total_available} rows (a key is needed)`;
  }
  if (scores.length < MIN_ROWS) return `only ${scores.length} rows (< ${MIN_ROWS})`;
  if (scores.some((r) => !r || !r.market_slug || !r.market_name || !r.state)) return 'a row is missing slug, name or state';
  const slugs = new Set(scores.map((r) => String(r.market_slug)));
  const lost = (current || []).filter((r) => !slugs.has(r[0]));
  if (current && current.length && lost.length > current.length * MAX_LOSS) {
    return `would drop ${lost.length} of ${current.length} committed markets (> ${MAX_LOSS * 100}%)`;
  }
  return null;
}

function render(rows, asOf) {
  return `// GENERATED by scripts/gen-dcpi-markets.mjs from /api/v1/dcpi/scores (as_of ${asOf}).
// Do not edit by hand; edit the generator's EXTRA/STATES and regenerate.
// Refreshed daily by .github/workflows/daily-manifest-sync.yml (written only when the rows change).
// Row: [slug, name, states, iso (the index's grid label), rto (US RTO or null), aliases]
export const DCPI_MARKETS_AS_OF = ${JSON.stringify(asOf)};
export const DCPI_MARKETS = [
${rows.map((r) => '  ' + JSON.stringify(r) + ',').join('\n')}
];
`;
}

async function load(src) {
  if (src) return JSON.parse(readFileSync(src, 'utf8'));
  const key = process.env.DCHUB_KEY || '';
  if (!key) throw new Error('DCHUB_KEY is not set (anonymous gets 10 of the rows)');
  const r = await fetch(URL_, {
    headers: { 'User-Agent': 'dchub-qa-readonly dchub-mcp-dcpi-markets-refresh/1.0', 'X-DCHub-QA': '1',
               'X-API-Key': key, Accept: 'application/json' },
    signal: AbortSignal.timeout(60000),
  });
  if (!r.ok) throw new Error('HTTP ' + r.status);
  return r.json();
}

async function main() {
  let body;
  try { body = await load(process.argv[2]); } catch (e) {
    console.log(`dcpi markets refresh: ${String(e && e.message || e)} — keeping the committed table`);
    return;
  }
  let current = null;
  try { current = (await import(pathToFileURL(fileURLToPath(OUT)).href)).DCPI_MARKETS; } catch (_e) { /* first run */ }
  const why = refuseReason(body, current);
  if (why) { console.log(`dcpi markets refresh: refusing (${why}) — keeping the committed table`); return; }
  const rows = buildRows(body.scores);
  if (current && JSON.stringify(current) === JSON.stringify(rows)) {
    console.log(`dcpi markets refresh: ${rows.length} markets, unchanged`);
    return;
  }
  writeFileSync(OUT, render(rows, body.as_of || null));
  const was = new Set((current || []).map((r) => r[0]));
  const now = new Set(rows.map((r) => r[0]));
  console.log(`dcpi markets refresh: wrote ${rows.length} markets (as_of ${body.as_of}); `
    + `added [${[...now].filter((s) => !was.has(s)).join(', ')}] removed [${[...was].filter((s) => !now.has(s)).join(', ')}]`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
