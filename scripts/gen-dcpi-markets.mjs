#!/usr/bin/env node
// Regenerates lib/dcpi-markets.data.mjs: every market the live DCPI index
// tracks, so execute_plan's market_outlook class can read "power outlook for
// <any tracked market>" as that market (lib/dcpi-market-match.mjs).
//
//   curl -sS 'https://dchub.cloud/api/v1/dcpi/scores?limit=500' > /tmp/dcpi.json
//   node scripts/gen-dcpi-markets.mjs /tmp/dcpi.json
//
// Each row: [slug, display name, state, iso, rto, aliases]. `iso` is the
// index's own grid label (WECC, SOCO, TVA, ENTSOE-DE …). `rto` is that label
// only when it is a US RTO execute_plan accepts as an iso arg, else null.
// Aliases are the normalized name plus the hand-kept EXTRA list below; review
// the diff when you regenerate — a new market whose name is an ordinary word
// belongs in QUALIFIER_REQUIRED in the matcher.
import { readFileSync, writeFileSync } from 'node:fs';
import { normPlace } from '../lib/dcpi-market-norm.mjs';

const RTOS = new Set(['ERCOT', 'PJM', 'MISO', 'SPP', 'CAISO', 'NYISO', 'ISONE']);
// Other names people use for a tracked market. Never a nearby market's name.
const EXTRA = {
  dallas: ['dallas fort worth', 'dfw'],
  'new-york': ['new york city', 'nyc'],
  'salt-lake-city': ['salt lake'],
  'midland-tx': ['midland', 'odessa', 'permian basin'],
  'the-woodlands': ['woodlands'],
  'virgin-islands': ['virgin islands', 'usvi'],
  'appalachia-coal': ['appalachia'],
  'upper-michigan': ['upper peninsula'],
  bangalore: ['bengaluru'],
  'ho-chi-minh-city': ['saigon', 'hcmc'],
  'mexico-city': ['cdmx'],
  'johor': ['johor bahru'],
  'bridgewater-township': ['bridgewater'],
  "coeur-d'alene": ['coeur d alene'],
  dc: ['washington dc', 'washington, dc', 'district of columbia'],
};
// A name followed by its own state ("Portland, ME") is the base name plus a
// qualifier, so "portland" is the alias. DC is the exception: its base name is
// a state.
const NO_BASE = new Set(['dc']);
// Markets that span more than one state.
const STATES = { 'kansas-city': ['MO', 'KS'] };

const src = process.argv[2];
if (!src) { console.error('usage: gen-dcpi-markets.mjs <dcpi scores json>'); process.exit(2); }
const body = JSON.parse(readFileSync(src, 'utf8'));
const scores = Array.isArray(body) ? body : body.scores;
if (!Array.isArray(scores) || scores.length < 100) {
  console.error(`refusing: expected the full index, got ${scores && scores.length} rows`); process.exit(1);
}
const titled = (n) => (n === n.toUpperCase() ? n.toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase()) : n);
const rows = scores.map((r) => {
  const slug = String(r.market_slug), state = String(r.state || '').toUpperCase(), iso = String(r.iso || '').toUpperCase() || null;
  const name = titled(String(r.market_name || slug));
  const aliases = new Set();
  const full = normPlace(name);
  const q = full.match(/^(.*), ([a-z]{2})$/);
  if (q && q[2].toUpperCase() === state) { if (!NO_BASE.has(slug)) aliases.add(q[1]); }
  else aliases.add(full.replace(/,/g, ''));
  for (const a of EXTRA[slug] || []) aliases.add(normPlace(a));
  return [slug, name, STATES[slug] || [state], iso, RTOS.has(iso) ? iso : null, [...aliases].sort()];
}).sort((a, b) => a[0].localeCompare(b[0]));

const asOf = body.as_of || null;
const out = `// GENERATED by scripts/gen-dcpi-markets.mjs from /api/v1/dcpi/scores (as_of ${asOf}).
// Do not edit by hand; edit the generator's EXTRA/STATES and regenerate.
// Row: [slug, name, states, iso (the index's grid label), rto (US RTO or null), aliases]
export const DCPI_MARKETS_AS_OF = ${JSON.stringify(asOf)};
export const DCPI_MARKETS = [
${rows.map((r) => '  ' + JSON.stringify(r) + ',').join('\n')}
];
`;
writeFileSync(new URL('../lib/dcpi-markets.data.mjs', import.meta.url), out);
console.log(`wrote ${rows.length} markets (as_of ${asOf})`);
