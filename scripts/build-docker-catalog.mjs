#!/usr/bin/env node
// =============================================================================
// build-docker-catalog — integrations/docker/catalog.yaml, the Docker MCP
// Toolkit catalog for DC Hub.
// -----------------------------------------------------------------------------
// WHY (2026-10-24). DC Hub's entry in Docker's own registry (docker/mcp-registry
// PR 4644, open since 2026-08-06, correct and mergeable) has never been
// reviewed: that repo has merged no new third-party entry since 2026-08-21, its
// main last moved 2026-09-16, and its PR checks have not run since May. The
// Docker MCP gateway does not need that queue, though: `docker mcp catalog
// import <url>` downloads any catalog file and adds it beside Docker's own, and
// `docker mcp catalog update` re-fetches it (docker/mcp-gateway
// cmd/docker-mcp/catalog/import.go). This file is that catalog, served from the
// repo's raw URL, so Docker Desktop users can add DC Hub with two commands.
//
// ONE SOURCE: toolspec.json (the live tools/list, refreshed by
// daily-manifest-sync) and canonical/listing-copy.json (the owner's copy). The
// format is docker/mcp-gateway pkg/catalog/types.go: top-level name +
// displayName + registry map; a remote server is type "remote" with remote.url
// and remote.transport_type. Strings are emitted JSON-quoted, which YAML reads
// as double-quoted scalars, so no description can break the file.
//
//   node scripts/build-docker-catalog.mjs          # print
//   node scripts/build-docker-catalog.mjs --fix    # write the file if it drifted
//   node scripts/build-docker-catalog.mjs --check  # exit 1 if it drifted
// =============================================================================
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadListingCopy, MCP_URL } from './listing-copy.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CATALOG_PATH = 'integrations/docker/catalog.yaml';
export const CATALOG_NAME = 'dchub';
export const SERVER_NAME = 'dchub';
export const RAW_URL = `https://raw.githubusercontent.com/azmartone67/dchub-mcp-server/main/${CATALOG_PATH}`;
export const README_URL = 'https://github.com/azmartone67/dchub-mcp-server/blob/main/integrations/docker/README.md';
export const ICON_URL = 'https://dchub.cloud/icons/icon-192.png';
export const TOOL_DESC_MAX = 200;

const q = (s) => JSON.stringify(String(s ?? ''));

/** A tool's catalog line: its first sentence, capped, never empty. */
export function shortToolDescription(desc) {
  const flat = String(desc || '').replace(/\s+/g, ' ').trim();
  const first = (flat.match(/^.*?[.!?](?=\s|$)/) || [flat])[0];
  if (first.length <= TOOL_DESC_MAX) return first;
  const cut = first.slice(0, TOOL_DESC_MAX - 1);
  return `${cut.slice(0, cut.lastIndexOf(' ') > 80 ? cut.lastIndexOf(' ') : cut.length)}…`;
}

/** The catalog text for this copy and these tools. Pure. */
export function buildCatalog(copy, tools) {
  if (!copy?.short) throw new Error('listing-copy.json has no short copy');
  if (!Array.isArray(tools) || !tools.length) throw new Error('toolspec.json has no tools');
  const sorted = [...tools].filter((t) => t?.name).sort((a, b) => a.name.localeCompare(b.name));
  const lines = [
    '# Docker MCP Toolkit catalog for DC Hub. GENERATED by scripts/build-docker-catalog.mjs',
    '# from toolspec.json and canonical/listing-copy.json; edit those, not this file.',
    '#',
    '#   docker mcp catalog import ' + RAW_URL,
    `#   docker mcp server enable ${SERVER_NAME}`,
    '#',
    '# `docker mcp catalog update` re-fetches this file.',
    `name: ${q(CATALOG_NAME)}`,
    `displayName: ${q('DC Hub')}`,
    'registry:',
    `  ${SERVER_NAME}:`,
    `    name: ${q(SERVER_NAME)}`,
    '    type: "remote"',
    `    title: ${q('DC Hub')}`,
    `    description: ${q(copy.short)}`,
    `    icon: ${q(ICON_URL)}`,
    `    readme: ${q(README_URL)}`,
    '    remote:',
    `      url: ${q(MCP_URL)}`,
    '      transport_type: "streamable-http"',
    '    metadata:',
    '      category: "data"',
    '      tags:',
    ...['data-center', 'energy', 'power-grid', 'site-selection', 'remote'].map((t) => `        - ${q(t)}`),
    '      license: "MIT"',
    `      owner: ${q('DC Hub (dchub.cloud)')}`,
    '    tools:',
    ...sorted.flatMap((t) => [`      - name: ${q(t.name)}`, `        description: ${q(shortToolDescription(t.description))}`]),
  ];
  return `${lines.join('\n')}\n`;
}

function readJson(rel) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
}

function main() {
  const mode = process.argv.includes('--fix') ? 'fix' : process.argv.includes('--check') ? 'check' : 'print';
  const want = buildCatalog(loadListingCopy(ROOT), readJson('toolspec.json'));
  const file = path.join(ROOT, CATALOG_PATH);
  const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (mode === 'print') { process.stdout.write(want); return; }
  if (have === want) { console.log(`✓ ${CATALOG_PATH} in sync`); return; }
  if (mode === 'check') {
    console.error(`✗ ${CATALOG_PATH} is behind toolspec.json / listing-copy.json. Run: node scripts/build-docker-catalog.mjs --fix`);
    process.exit(1);
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, want);
  console.log(`wrote: ${CATALOG_PATH}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
